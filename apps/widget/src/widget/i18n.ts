export type MessageKey = keyof (typeof STRINGS)['es'];
export type Translate = (key: MessageKey, params?: Record<string, string | number>) => string;

export function translator(locale: string | undefined): Translate {
  const language = (locale || 'es').slice(0, 2) as keyof typeof STRINGS;
  const table = STRINGS[language] ?? STRINGS.es;
  return (key, params) => {
    let value: string = table[key] ?? STRINGS.es[key];
    for (const [name, replacement] of Object.entries(params ?? {})) {
      value = value.replace(`{${name}}`, String(replacement));
    }
    return value;
  };
}
