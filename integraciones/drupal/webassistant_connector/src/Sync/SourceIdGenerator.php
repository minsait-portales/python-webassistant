<?php

declare(strict_types=1);

namespace Drupal\webassistant_connector\Sync;

use Drupal\Core\Config\ConfigFactoryInterface;

/**
 * Builds and parses remote source IDs (design section 8.3, step 5).
 *
 * Format: {prefix}:{entity_type}:{id}:{langcode}, e.g. drupal:node:42:es;
 * attachments append :file:{uuid}. The prefix is sync.source_id_prefix
 * (amendment A10). Every segment is encoded so the ID matches the canonical
 * pattern ^[A-Za-z0-9_.:/@-]+$ and splits unambiguously on ":": characters
 * outside [A-Za-z0-9_.-] (including ":", "/" and "@") become "@" followed by
 * two upper-case hex digits of each byte (e.g. "a:b" -> "a@3Ab").
 *
 * IDs whose entity segment would make the source ID longer than MAX_LENGTH
 * (keeping room for an attachment suffix) use "@h" plus the SHA-256 of the
 * entity ID instead: such IDs are not parseable (parse() returns NULL) and
 * are only matched through the document map.
 *
 * Service: webassistant_connector.source_id_generator.
 */
final class SourceIdGenerator {

  /**
   * Prefix used when sync.source_id_prefix is missing or invalid.
   */
  public const DEFAULT_PREFIX = 'drupal';

  /**
   * Pattern of the configurable prefix (amendment A10).
   */
  public const PREFIX_PATTERN = '/^[a-z][a-z0-9_.-]{1,31}$/';

  /**
   * Pattern of remote source IDs (canonical-document.v1).
   */
  public const SOURCE_ID_PATTERN = '/^[A-Za-z0-9_.:\/@-]{1,256}$/';

  /**
   * Maximum length of a remote source ID (canonical-document.v1).
   */
  public const MAX_LENGTH = 256;

  /**
   * Maximum length of a base source ID: room for ":file:{uuid}" (42).
   */
  public const MAX_BASE_LENGTH = 200;

  /**
   * Segment separating the attachment UUID.
   */
  private const ATTACHMENT_SEGMENT = 'file';

  /**
   * Constructs a SourceIdGenerator.
   *
   * @param \Drupal\Core\Config\ConfigFactoryInterface $configFactory
   *   The config factory.
   */
  public function __construct(
    private readonly ConfigFactoryInterface $configFactory,
  ) {}

  /**
   * Returns the configured prefix (sync.source_id_prefix).
   *
   * @return string
   *   The prefix, or DEFAULT_PREFIX when the configured one is invalid.
   */
  public function getPrefix(): string {
    $prefix = $this->configFactory->get('webassistant_connector.settings')->get('sync.source_id_prefix');
    return is_string($prefix) && preg_match(self::PREFIX_PATTERN, $prefix) ? $prefix : self::DEFAULT_PREFIX;
  }

  /**
   * Builds the source ID of a translation.
   *
   * @param string $entityTypeId
   *   The entity type ID.
   * @param int|string $entityId
   *   The entity ID.
   * @param string $langcode
   *   The Drupal language code.
   *
   * @return string
   *   E.g. drupal:node:42:es (characters outside [A-Za-z0-9_.:/@-] are
   *   encoded so the result matches the canonical pattern).
   */
  public function generate(string $entityTypeId, int|string $entityId, string $langcode): string {
    $head = $this->getPrefix() . ':' . self::encode($entityTypeId);
    $tail = ':' . self::encode($langcode);
    $id = self::encode((string) $entityId);
    if (strlen($head) + 1 + strlen($id) + strlen($tail) > self::MAX_BASE_LENGTH) {
      $id = '@h' . hash('sha256', (string) $entityId);
    }
    return $head . ':' . $id . $tail;
  }

  /**
   * Builds the source ID of an attached file.
   *
   * @param string $baseSourceId
   *   The source ID of the entity translation.
   * @param string $fileUuid
   *   The file UUID.
   *
   * @return string
   *   {base}:file:{uuid}.
   */
  public function forAttachment(string $baseSourceId, string $fileUuid): string {
    return $baseSourceId . ':' . self::ATTACHMENT_SEGMENT . ':' . self::encode($fileUuid);
  }

  /**
   * Whether a remote source ID was generated by this installation.
   *
   * @param string $sourceId
   *   The remote source ID.
   *
   * @return bool
   *   TRUE if it starts with "{prefix}:".
   */
  public function isOwn(string $sourceId): bool {
    return str_starts_with($sourceId, $this->getPrefix() . ':');
  }

  /**
   * Parses a source ID generated by this installation.
   *
   * @param string $sourceId
   *   The remote source ID.
   *
   * @return array{entity_type: string, entity_id: string, langcode: string, attachment: string|null}|null
   *   The parts, or NULL if the ID is not ours, is malformed or uses a hashed
   *   entity ID.
   */
  public function parse(string $sourceId): ?array {
    if (!$this->isOwn($sourceId) || !preg_match(self::SOURCE_ID_PATTERN, $sourceId)) {
      return NULL;
    }
    $parts = explode(':', substr($sourceId, strlen($this->getPrefix()) + 1));
    $count = count($parts);
    if ($count !== 3 && !($count === 5 && $parts[3] === self::ATTACHMENT_SEGMENT)) {
      return NULL;
    }
    $decoded = [];
    foreach ($parts as $index => $part) {
      if ($index === 3) {
        continue;
      }
      $value = self::decode($part);
      if ($value === NULL || $value === '') {
        return NULL;
      }
      $decoded[$index] = $value;
    }
    if (!preg_match('/^[a-z][a-z0-9_]*$/', $decoded[0]) || !preg_match('/^[a-zA-Z0-9_-]+$/', $decoded[2])) {
      return NULL;
    }
    return [
      'entity_type' => $decoded[0],
      'entity_id' => $decoded[1],
      'langcode' => $decoded[2],
      'attachment' => $decoded[4] ?? NULL,
    ];
  }

  /**
   * Encodes a segment: bytes outside [A-Za-z0-9_.-] become "@XX".
   *
   * @param string $value
   *   The raw segment.
   *
   * @return string
   *   The encoded segment.
   */
  public static function encode(string $value): string {
    return (string) preg_replace_callback(
      '/[^A-Za-z0-9_.-]/',
      static fn (array $match): string => '@' . strtoupper(bin2hex($match[0])),
      $value,
    );
  }

  /**
   * Decodes a segment built by encode().
   *
   * @param string $value
   *   The encoded segment.
   *
   * @return string|null
   *   The raw segment, or NULL if it is not a valid encoding (e.g. a hashed
   *   entity ID or a stray "/").
   */
  public static function decode(string $value): ?string {
    if (!preg_match('/^(?:[A-Za-z0-9_.-]|@[0-9A-F]{2})*$/', $value)) {
      return NULL;
    }
    return (string) preg_replace_callback(
      '/@([0-9A-F]{2})/',
      static fn (array $match): string => (string) hex2bin($match[1]),
      $value,
    );
  }

}
