<?php

declare(strict_types=1);

namespace Drupal\webassistant_connector\Sync;

use Drupal\Component\Utility\UrlHelper;
use Drupal\Core\Config\ConfigFactoryInterface;
use Drupal\Core\Entity\EntityInterface;
use Drupal\Core\Entity\Exception\UndefinedLinkTemplateException;
use Drupal\Core\File\FileUrlGeneratorInterface;
use Drupal\Core\Url;
use Symfony\Component\HttpFoundation\RequestStack;

/**
 * Builds absolute URLs for documents (design section 8.3, step 8).
 *
 * Uses sync.public_base_url when set (mandatory in CLI/cron when the public
 * host differs), otherwise the current request scheme, host and base path.
 *
 * Service: webassistant_connector.url_resolver.
 */
final class UrlResolver {

  /**
   * Base URL used when there is neither a configured URL nor a request.
   */
  private const FALLBACK_BASE_URL = 'http://localhost';

  /**
   * Constructs a UrlResolver.
   *
   * @param \Drupal\Core\Config\ConfigFactoryInterface $configFactory
   *   The config factory.
   * @param \Symfony\Component\HttpFoundation\RequestStack $requestStack
   *   The request stack.
   * @param \Drupal\Core\File\FileUrlGeneratorInterface $fileUrlGenerator
   *   The file URL generator.
   */
  public function __construct(
    private readonly ConfigFactoryInterface $configFactory,
    private readonly RequestStack $requestStack,
    private readonly FileUrlGeneratorInterface $fileUrlGenerator,
  ) {}

  /**
   * Returns the base URL used for absolute URLs, without trailing slash.
   *
   * @return string
   *   sync.public_base_url, or the current scheme://host[:port]/base-path.
   */
  public function getBaseUrl(): string {
    $configured = $this->getPublicBaseUrl();
    if ($configured !== NULL) {
      return $configured;
    }
    $request = $this->requestStack->getCurrentRequest();
    if ($request === NULL) {
      return self::FALLBACK_BASE_URL;
    }
    return rtrim($request->getSchemeAndHttpHost() . $request->getBasePath(), '/');
  }

  /**
   * Returns the absolute canonical URL of an entity translation.
   *
   * The URL keeps the language prefix or domain of the translation (outbound
   * path processors still run); only the scheme, host and base path come
   * from sync.public_base_url when it is set.
   *
   * @param \Drupal\Core\Entity\EntityInterface $entity
   *   The entity (in the wanted translation).
   *
   * @return string|null
   *   The absolute http(s) URL, or NULL if the entity has no canonical link.
   */
  public function canonicalUrl(EntityInterface $entity): ?string {
    if ($entity->isNew() || !$entity->hasLinkTemplate('canonical')) {
      return NULL;
    }
    try {
      $url = $entity->toUrl('canonical', ['absolute' => TRUE]);
      return $this->absoluteFromUrl($url);
    }
    catch (UndefinedLinkTemplateException) {
      return NULL;
    }
  }

  /**
   * Builds the absolute string of a Url object against getBaseUrl().
   *
   * @param \Drupal\Core\Url $url
   *   The URL (routed, internal or external).
   *
   * @return string|null
   *   The absolute http(s) URL, or NULL if it cannot be made absolute.
   */
  public function absoluteFromUrl(Url $url): ?string {
    $url = clone $url;
    $url->setAbsolute(TRUE);
    $configured = $this->getPublicBaseUrl();
    if ($configured !== NULL && !$url->isExternal()) {
      // UrlGenerator::generateFromRoute() uses base_url instead of the
      // request context; language negotiation by domain may still override
      // it, which is the expected public host of that language.
      $url->setOption('base_url', $configured);
    }
    $generated = $url->toString(TRUE)->getGeneratedUrl();
    $absolute = $this->toAbsolute($generated);
    return preg_match('#^https?://#i', $absolute) ? $absolute : NULL;
  }

  /**
   * Makes a URL absolute against getBaseUrl().
   *
   * @param string $url
   *   An absolute URL (returned as is) or a root-relative path. Root-relative
   *   paths generated by Drupal already contain the base path of the current
   *   request; it is replaced by the base path of the public URL.
   *
   * @return string
   *   The absolute URL.
   */
  public function toAbsolute(string $url): string {
    if (preg_match('#^[a-z][a-z0-9+.-]*://#i', $url)) {
      return $url;
    }
    $base = $this->getBaseUrl();
    if (str_starts_with($url, '//')) {
      $scheme = parse_url($base, PHP_URL_SCHEME) ?: 'https';
      return $scheme . ':' . $url;
    }
    if (!str_starts_with($url, '/')) {
      return $base . '/' . $url;
    }
    $request = $this->requestStack->getCurrentRequest();
    $basePath = $request !== NULL ? rtrim($request->getBasePath(), '/') : '';
    if ($basePath !== '' && ($url === $basePath || str_starts_with($url, $basePath . '/'))) {
      $url = substr($url, strlen($basePath)) ?: '/';
    }
    return $base . $url;
  }

  /**
   * Returns the absolute URL of a file URI (e.g. public://image.png).
   *
   * @param string $uri
   *   The file URI.
   *
   * @return string
   *   The absolute URL against getBaseUrl().
   */
  public function fileUrl(string $uri): string {
    return $this->toAbsolute($this->fileUrlGenerator->generateString($uri));
  }

  /**
   * Returns sync.public_base_url when it is a valid http(s) URL.
   *
   * @return string|null
   *   The URL without trailing slash, or NULL.
   */
  private function getPublicBaseUrl(): ?string {
    $configured = trim((string) $this->configFactory->get('webassistant_connector.settings')->get('sync.public_base_url'));
    if ($configured === '' || !preg_match('#^https?://#i', $configured) || !UrlHelper::isValid($configured, TRUE)) {
      return NULL;
    }
    return rtrim($configured, '/');
  }

}
